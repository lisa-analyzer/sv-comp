# Standard library imports
from collections import Counter
from dataclasses import dataclass

# Project-local imports
from cli.models.lisa_report.fields.info import Info
from cli.models.lisa_report.fields.notice import Notice
from cli.models.lisa_report.fields.warning import Warning


@dataclass
class LisaReport:
    """
    Represents the 'report' JSON file generated by LiSA
    """

    # There are other fields (files, configuration, etc.) in the report. Add them up upon the need
    warnings: list[Warning]
    notices: list[Notice]
    info: Info

    def __init__(self, warnings, info, notices=(), **_):
        self.warnings = [Warning(**w) if isinstance(w, dict) else w for w in warnings]
        self.notices = [Notice(**n) if isinstance(n, dict) else n for n in notices]
        self.info = Info(**info)

    def has_warnings(self) -> bool:
        return self.info.warnings > 0

    def has_notices(self) -> bool:
        return self.info.notices > 0

    def list_warnings(self) -> list[str]:
        return [w.message for w in self.warnings]

    def list_notices(self) -> list[str]:
        return [n.extract_notice() for n in self.notices]

    # assert specific

    def list_assert_warnings(self) -> list[Warning]:
        return [w for w in self.warnings if w.is_assertion_warning()]

    def has_assert_warnings(self) -> bool:
        return len(self.list_assert_warnings()) > 0

    def has_definite_assert_warning(self) -> bool:
        return any(w.definite for w in self.list_assert_warnings())

    def has_possible_assert_warning(self) -> bool:
        return any(w.is_possible() for w in self.list_assert_warnings())

    def has_only_refuted_assert_warnings(self) -> bool:
        return all(w.refuted for w in self.list_assert_warnings())

    def count_possible_assert_reasons(self) -> Counter:
        """
        How many possible assertion warnings the verification left possible for each reason
        """
        return self.__count_possible_reasons(self.list_assert_warnings())

    # runtime specific

    def list_runtime_warnings(self) -> list[Warning]:
        return [w for w in self.warnings if w.is_runtime_warning()]

    def has_runtime_warnings(self) -> bool:
        return len(self.list_runtime_warnings()) > 0

    def has_definite_runtime_warning(self) -> bool:
        return any(w.definite for w in self.list_runtime_warnings())

    def has_possible_runtime_warning(self) -> bool:
        return any(w.is_possible() for w in self.list_runtime_warnings())

    def has_only_refuted_runtime_warnings(self) -> bool:
        return all(w.refuted for w in self.list_runtime_warnings())

    def count_possible_runtime_reasons(self) -> Counter:
        """
        How many possible runtime exception warnings the verification left possible for each reason
        """
        return self.__count_possible_reasons(self.list_runtime_warnings())

    @staticmethod
    def __count_possible_reasons(warnings: list[Warning]) -> Counter:
        reasons = Counter()
        for w in warnings:
            reasons.update(w.possible_reasons())
        return reasons

    # notice specific

    def get_bottom_notices(self) -> int:
        return [n for n in self.notices if n.is_bottom_notice()]

    def count_bottom_notices(self) -> int:
        return sum(1 for n in self.notices if n.is_bottom_notice())

    def has_bottom_notices(self) -> bool:
        return self.count_bottom_notices() > 0

    def get_open_call_notices(self) -> int:
        return [n for n in self.notices if n.is_open_call_notice()]

    def count_open_call_notices(self) -> int:
        return sum(1 for n in self.notices if n.is_open_call_notice())

    def has_open_call_notices(self) -> bool:
        return self.count_open_call_notices() > 0
